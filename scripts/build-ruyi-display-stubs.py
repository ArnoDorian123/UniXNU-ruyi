#!/usr/bin/env python3
"""Build the display stub archive in the shape the kernel link expects.

Background
----------
scripts/build-xnu-4k-baseline.sh force-loads a legacy display archive when
XNU_NATIVE_LEGACY_DISPLAY=1, at a fixed path:

    $ROOT/build/native-legacy-display/libNativeLegacyDisplay.late.a

and before linking it verifies the sibling build-report.json:

    archive_sha256    sha256 of the archive itself
    source_sha256     {path relative to ROOT: sha256}

sheng satisfies that contract with scripts/build-native-legacy-display.py, which needs the
sheng audit reference data. ruyi has none, so this builder emits the same layout with a stub
implementation. The probe reports "no legacy display", and the kernel keeps using the
framebuffer DarwinBoot handed over.

A separate archive plus CONFIG_XNU_EXTRA_LD_ARCHIVES does not work here: that value is
appended to the link line verbatim, without -force_load, so the stub object is never pulled.

Replace this builder once ruyi has a real display driver.
"""

import hashlib
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "build" / "native-legacy-display"
OUT.mkdir(parents=True, exist_ok=True)

SOURCE = OUT / "NativeLegacyDisplayStub.c"
OBJECT = OUT / "NativeLegacyDisplayStub.o"
ARCHIVE = OUT / "libNativeLegacyDisplay.late.a"
REPORT = OUT / "build-report.json"

SOURCE.write_text(
    "/* Generated by scripts/build-ruyi-display-stubs.py. Do not edit. */\n"
    "\n"
    "/*\n"
    " * Return 0: there is no legacy display path on this board yet. Callers treat a\n"
    " * non-zero result as \"handled\", so 0 leaves the boot on the DarwinBoot\n"
    " * framebuffer instead of driving the panel from the kernel.\n"
    " */\n"
    "int native_legacy_display_probe(void) { return 0; }\n"
    "int native_legacy_display_late_probe(void) { return 0; }\n",
    encoding="utf-8",
)

subprocess.run(
    [
        "xcrun", "--sdk", "iphoneos", "clang",
        "-target", "arm64-apple-ios17.0",
        "-O2", "-ffreestanding", "-fno-builtin", "-fno-stack-protector",
        "-c", str(SOURCE), "-o", str(OBJECT),
    ],
    check=True,
)
subprocess.run(["xcrun", "ar", "rcs", str(ARCHIVE), str(OBJECT)], check=True)

REPORT.write_text(
    json.dumps(
        {
            "archive_sha256": hashlib.sha256(ARCHIVE.read_bytes()).hexdigest(),
            "source_sha256": {},
            "note": "ruyi display stub; no owned sources yet",
        },
        indent=2,
    )
    + "\n"
)

print(ARCHIVE)
sys.exit(0)
