#!/usr/bin/env python3
"""Build the ruyi display stub archive.

The XNU tree used by UniXNU is patched so that bsd_init() and bsd_autoconf() call
native_legacy_display_probe() and native_legacy_display_late_probe(), and the native
mobile graphics client calls the former too. Those calls are unconditional, so every
board has to provide the symbols even when it does not implement the legacy display
path yet.

sheng provides them through scripts/build-native-legacy-display.py, which needs the
sheng audit reference data. ruyi does not have that data, so this builder emits a
minimal stub archive instead. The archive is attached to the kernel link through
CONFIG_XNU_EXTRA_LD_ARCHIVES.

Replace this builder once ruyi has a real NativeMobileDisplay/NativeLegacyDisplay
driver: the stubs make the probe report "no display" and the kernel keeps using the
framebuffer that DarwinBoot handed over.
"""

import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "build" / "ruyi-display-stubs"
OUT.mkdir(parents=True, exist_ok=True)

SOURCE = OUT / "ruyi_display_stubs.c"
OBJECT = OUT / "ruyi_display_stubs.o"
ARCHIVE = OUT / "libRuyiDisplayStubs.a"

SOURCE.write_text(
    "/* Generated by scripts/build-ruyi-display-stubs.py. Do not edit. */\n"
    "\n"
    "/*\n"
    " * Return 0: the legacy display path is not present. Callers treat a non-zero\n"
    " * result as \"handled\", so 0 keeps the boot path on the DarwinBoot framebuffer.\n"
    " */\n"
    "int native_legacy_display_probe(void) { return 0; }\n"
    "int native_legacy_display_late_probe(void) { return 0; }\n",
    encoding="utf-8",
)

CC = [
    "xcrun", "--sdk", "iphoneos", "clang",
    "-target", "arm64-apple-ios17.0",
    "-O2", "-ffreestanding", "-fno-builtin", "-fno-stack-protector",
    "-c", str(SOURCE), "-o", str(OBJECT),
]

subprocess.run(CC, check=True)
subprocess.run(["xcrun", "ar", "rcs", str(ARCHIVE), str(OBJECT)], check=True)

print(ARCHIVE)
sys.exit(0)
